"""Step 1: locate inputs, stage raw files unchanged, and write the data inventory + inspection notes."""
import _bootstrap  # noqa: F401
from collections import Counter

import numpy as np

from battery_project import artifacts, cleaning, data_loader
from battery_project.config import ROOT, ensure_dirs, load_config

UNITS = {  # from the supplied README
    "Voltage_measured": "V", "Current_measured": "A", "Temperature_measured": "degC", "Current_charge": "A",
    "Voltage_charge": "V", "Current_load": "A", "Voltage_load": "V", "Time": "s", "Capacity": "Ah",
    "Sense_current": "A", "Battery_current": "A", "Current_ratio": "-", "Battery_impedance": "ohm",
    "Rectified_Impedance": "ohm", "Re": "ohm", "Rct": "ohm",
}


def main():
    cfg = load_config(); ensure_dirs(cfg)
    found, missing, notes = data_loader.stage_raw_files(cfg)
    for n in notes:
        print(n)
    if missing:
        print(f"MISSING battery files (place them in {cfg['paths']['raw_dir']}): {missing}")
    if not found:
        raise SystemExit("No battery .mat files found; nothing to inspect.")

    inv = {"raw_dir": cfg["paths"]["raw_dir"], "found": list(found), "missing": missing, "batteries": {}}
    pptx = sorted(p.name for p in ROOT.glob("*.pptx"))
    inv["presentation_files"] = pptx
    inv["documentation_present"] = [d for d in cfg["documentation_files"] if (cfg["paths"]["raw_dir"] / d).exists()]
    for bid, path in found.items():
        recs = data_loader.load_battery(path, bid)
        recs, warns = cleaning.validate_records(recs)
        recs = cleaning.number_operations(recs)
        ops = Counter(r["op_type"] for r in recs)
        fields = {}
        for r in recs:
            f = fields.setdefault(r["op_type"], Counter())
            for k in list(r["signals"]) + list(r["scalars"]) + list(r["complex_fields"]):
                f[k] += 1
        dis = [r for r in recs if r["op_type"] == "discharge"]
        chg = [r for r in recs if r["op_type"] == "charge"]
        imp = [r for r in recs if r["op_type"] == "impedance"]
        load_sign = Counter("positive" if np.median(r["signals"]["Current_load"]) > 0 else "negative" for r in dis)
        caps = np.array([r["scalars"].get("Capacity", np.nan) for r in dis])
        times = [r["start_time"] for r in recs if r["start_time"]]
        inv["batteries"][bid] = {
            "file": path.name, "sha256": data_loader.sha256(path), "bytes": path.stat().st_size,
            "records": len(recs), "operation_counts": dict(ops),
            "fields_by_operation": {op: {k: {"records_with_field": n, "unit": UNITS.get(k, "?")} for k, n in f.items()}
                                    for op, f in fields.items()},
            "ambient_temperature_C": sorted({r["ambient_temperature_C"] for r in recs}),
            "first_record_start": min(times), "last_record_start": max(times),
            "samples_per_record": {op: [int(min(r["n_samples"] for r in recs if r["op_type"] == op)),
                                        int(np.median([r["n_samples"] for r in recs if r["op_type"] == op])),
                                        int(max(r["n_samples"] for r in recs if r["op_type"] == op))] for op in ops
                                   if op != "impedance"},
            "charge_records_below_50_samples": sum(r["n_samples"] < 50 for r in chg),
            "discharge_capacity_Ah_min_max": [float(np.nanmin(caps)), float(np.nanmax(caps))],
            "discharge_capacity_missing": int(np.sum(~np.isfinite(caps))),
            "discharge_median_current_measured_A": float(np.median([np.median(r["signals"]["Current_measured"]) for r in dis])),
            "discharge_current_load_sign_by_record": dict(load_sign),
            "discharge_start_voltage_min_V": float(min(r["signals"]["Voltage_measured"][0] for r in dis)),
            "discharge_min_voltage_range_V": [float(min(r["signals"]["Voltage_measured"].min() for r in dis)),
                                              float(max(r["signals"]["Voltage_measured"].min() for r in dis))],
            "Re_ohm_min_max": [float(min(r["scalars"]["Re"] for r in imp)), float(max(r["scalars"]["Re"] for r in imp))] if imp else None,
            "Rct_ohm_min_max": [float(min(r["scalars"]["Rct"] for r in imp)), float(max(r["scalars"]["Rct"] for r in imp))] if imp else None,
            "parser_warnings": warns,
        }
    artifacts.write_json(inv, cfg["paths"]["results_dir"] / "data_inventory.json")
    write_markdown(cfg, inv)
    print(f"Wrote {cfg['paths']['results_dir'] / 'data_inventory.json'} and data_inspection.md")


def write_markdown(cfg, inv):
    L = ["# Data inspection", "",
         "Generated by `python scripts/inspect_data.py` from the files actually present. Machine-readable inventory: `results/data_inventory.json`.", "",
         "## Inputs", "",
         f"- Battery files found (copied unchanged to `data/raw/`, sha256 recorded): {', '.join(inv['found'])}",
         f"- Missing battery files: {', '.join(inv['missing']) or 'none'}",
         f"- Documentation: {', '.join(inv['documentation_present']) or 'none'}; presentation: {', '.join(inv['presentation_files']) or 'none'}",
         "- The presentation states project objectives only (SOH estimation, exploratory SOC prediction, LR/DT/RF comparison with MAE/RMSE/R², dashboard). "
         "It contains no measured results, so nothing from it is used as evidence.", "",
         "## Structure (observed)", "",
         "Each file is MATLAB v5 (readable by `scipy.io.loadmat`) with one struct `<BatteryID>` holding `cycle`, a 1×N struct array. "
         "Each element has `type` (charge / discharge / impedance), `ambient_temperature`, `time` (MATLAB date vector) and `data`.", "",
         "| Battery | Records | charge | discharge | impedance | Capacity range (Ah) | Truncated charge records (<50 samples) | First → last record start |",
         "|---|---|---|---|---|---|---|---|"]
    for b, d in inv["batteries"].items():
        oc = d["operation_counts"]; c = d["discharge_capacity_Ah_min_max"]
        L.append(f"| {b} | {d['records']} | {oc.get('charge', 0)} | {oc.get('discharge', 0)} | {oc.get('impedance', 0)} | "
                 f"{c[0]:.3f} – {c[1]:.3f} | {d['charge_records_below_50_samples']} | {d['first_record_start']:%Y-%m-%d} → {d['last_record_start']:%Y-%m-%d} |")
    first = next(iter(inv["batteries"].values()))
    L += ["", "Fields present (identical across all inspected files):", ""]
    for op, f in first["fields_by_operation"].items():
        L.append(f"- **{op}**: " + ", ".join(f"`{k}` ({v['unit']})" for k, v in f.items()))
    L += ["", "## Findings and limitations", "",
          "- **Field names differ from the README for discharge:** the files contain `Current_load` / `Voltage_load`, not `Current_charge` / `Voltage_charge`.",
          "- **Current sign:** `Current_measured` is ≈ +1.5 A during CC charge and ≈ −2 A during discharge (median discharge current per battery: "
          + ", ".join(f"{b} {d['discharge_median_current_measured_A']:.2f} A" for b, d in inv["batteries"].items()) + ").",
          "- **`Current_load` sign is inconsistent between discharge records** ("
          + "; ".join(f"{b}: {d['discharge_current_load_sign_by_record']}" for b, d in inv["batteries"].items())
          + "). It is not used for integration or as a model input.",
          "- **Ambient temperature** is 24 °C in every record, so it carries no information for modelling.",
          "- **Truncated charge records:** some charge records contain only a handful of samples; their charge features are left missing (not zero).",
          "- **Discharge cutoffs differ** (README: 2.7, 2.5, 2.2, 2.5 V for B0005/6/7/18), but `Capacity` is documented as capacity to 2.7 V. "
          "Integrating current to the 2.7 V crossing agrees with `Capacity` to within about 0.6 % (details in `results/soc_assessment.md`).",
          "- **Rated capacity:** the README gives 2 Ah (EOL = 30 % fade, 2 → 1.4 Ah). B0006's first measured capacities exceed 2 Ah, so its early SOH values are above 100 %. These are kept unclipped.",
          "- **Suspect charge records:** the charge immediately before discharge #31 in B0005/B0006/B0007 (record 84) reads a terminal voltage above 8 V, which is "
          "impossible for a cell charged at 4.2 V. The raw data are kept, but features from any charge record above 4.5 V are set to missing and flagged in `charge_feature_flag`. "
          "One B0018 charge record (114) contains non-finite samples.",
          "- **Impedance:** `Re` and `Rct` are real scalars per test, all positive and finite. Not every discharge is preceded by an impedance test "
          "(B0005–B0007: none before discharges 1–19 and a few later ones; B0018: "
          f"{inv['batteries'].get('B0018', {}).get('operation_counts', {}).get('impedance', 'n/a')} tests in total). "
          "Per-battery match coverage is in `results/tables/soh_match_coverage.csv`. Unmatched cycles keep missing impedance values; nothing is forward-filled.",
          "- The impedance spectra (`Battery_impedance`, `Rectified_Impedance`, complex) are not used beyond `Re`/`Rct`.",
          "- **No measured SOC exists** in the files; any SOC target must be a derived reference.", "",
          "## Parser warnings", ""]
    any_w = False
    for b, d in inv["batteries"].items():
        for w in d["parser_warnings"]:
            L.append(f"- {w}"); any_w = True
    if not any_w:
        L.append("- None: all signals finite, equal-length per record, and time strictly increasing within every record.")
    (cfg["paths"]["results_dir"] / "data_inspection.md").write_text("\n".join(L) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
